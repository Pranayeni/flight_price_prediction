import os
import streamlit as st
import pandas as pd
import numpy as np
import joblib

# ── Page Config ───────────────────────────────────────────────────────────────
st.set_page_config(
    page_title="Flight Price Predictor",
    page_icon="✈️",
    layout="centered"
)

# ── Load Pipeline (Updated with Error Fix) ────────────────────────────────────
@st.cache_resource
def load_pipeline():
    # 1. Identify the current directory where app.py is located
    base_dir = os.path.dirname(os.path.abspath(__file__))
    
    # 2. Construct the full path to the model file
    model_path = os.path.join(base_dir, "flight_price_best_pipeline.pkl")
    
    # 3. Check if the file exists before attempting to load
    if not os.path.exists(model_path):
        st.error("### ❌ Model File Not Found")
        st.info(f"The app is looking for the model file at: \n`{model_path}`")
        st.markdown("""
        **How to fix this:**
        1. Locate the file `flight_price_best_pipeline.pkl` generated by your notebook.
        2. Move or copy that file into the folder path shown above.
        3. Refresh this page.
        """)
        st.stop() # Prevents the app from crashing with a Traceback error
        
    return joblib.load(model_path)

# Initialize the pipeline
pipeline = load_pipeline()

# ── Header ────────────────────────────────────────────────────────────────────
st.title("✈️ Flight Price Predictor")
st.markdown("Fill in the flight details below to get a price estimate.")
st.divider()

col1, col2 = st.columns(2)

with col1:
    airline = st.selectbox("Airline", [
        "Air_India", "AirAsia", "GO_FIRST", "Indigo", "SpiceJet", "Vistara"
    ])

    source_city = st.selectbox("Source City", [
        "Bangalore", "Chennai", "Delhi", "Hyderabad", "Kolkata", "Mumbai"
    ])

    destination_city = st.selectbox("Destination City", [
        "Delhi", "Bangalore", "Chennai", "Hyderabad", "Kolkata", "Mumbai"
    ])

    departure_time = st.selectbox("Departure Time", [
        "Early_Morning", "Morning", "Afternoon", "Evening", "Night", "Late_Night"
    ])

with col2:
    arrival_time = st.selectbox("Arrival Time", [
        "Morning", "Early_Morning", "Afternoon", "Evening", "Night", "Late_Night"
    ])

    stops = st.selectbox("Number of Stops", [
        "zero", "one", "two_or_more"
    ])

    travel_class = st.selectbox("Class", ["Economy", "Business"])

    duration = st.number_input(
        "Duration (hours)",
        min_value=0.5, max_value=50.0,
        value=2.0, step=0.5
    )

    days_left = st.number_input(
        "Days Left to Departure",
        min_value=1, max_value=49,
        value=15, step=1
    )

st.divider()

# ── Predict ───────────────────────────────────────────────────────────────────
if st.button("🔍 Predict Price", use_container_width=True, type="primary"):

    if source_city == destination_city:
        st.warning("⚠️ Source and destination cities cannot be the same.")
    else:
        input_df = pd.DataFrame([{
            "airline"          : airline,
            "source_city"      : source_city,
            "departure_time"   : departure_time,
            "stops"            : stops,
            "arrival_time"     : arrival_time,
            "destination_city" : destination_city,
            "class"            : travel_class,
            "duration"         : float(duration),
            "days_left"        : int(days_left)
        }])

        # Pipeline handles preprocessing + prediction in one step
        log_prediction = pipeline.predict(input_df)[0]

        # Reverse log1p to get actual price in ₹
        prediction = np.expm1(log_prediction)

        st.success(f"### 💰 Estimated Flight Price: ₹ {prediction:,.0f}")
        st.caption("Prediction is based on a Random Forest Regressor · Test R² = 0.9765")

        st.info(f"""
**Flight Summary:**
- ✈️ **Airline:** {airline}
- 🛫 **Route:** {source_city} → {destination_city}
- 🕐 **Departure:** {departure_time} &nbsp;|&nbsp; **Arrival:** {arrival_time}
- 🛑 **Stops:** {stops}
- ⏱️ **Duration:** {duration} hrs
- 📅 **Days Left:** {days_left}
- 💺 **Class:** {travel_class}
        """)